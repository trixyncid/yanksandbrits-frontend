export function getFullScheduleEventsForDate(date: Date): TimetableEvent[] {
  const dayIndex = date.getDay()
  // Map Sunday(0)...Saturday(6) onto our weekday sets where index 0 = Monday.
  const mappedIndex = dayIndex === 0 ? 6 : dayIndex - 1
  const events = weekdayEventSets[mappedIndex] ?? weekdayEventSets[0]

  const dateKey = `${date.getFullYear()}-${date.getMonth() + 1}-${date.getDate()}`

  return events.map((event) => ({
    ...event,
    id: `${dateKey}-${event.id}`,
  }))
}
